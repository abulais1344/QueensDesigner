function toProduct({ soldOut = [], lowStock, ...rest }: SeedProduct): Product {
  const available = rest.sizes.filter((size) => !soldOut.includes(size))
  const stock: Product['stock'] = {}
  rest.sizes.forEach((size) => {
    const position = available.indexOf(size)
    if (position === -1) stock[size] = 0
    // Nearly sold out: one piece left in the first few sizes only.
    else if (lowStock) stock[size] = position < lowStock ? 1 : 0
    else stock[size] = 4 + ((rest.rank * 7 + position * 5) % 11)
  })
  return { ...rest, stock }
}

